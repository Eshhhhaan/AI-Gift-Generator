import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

const SYSTEM_PROMPT = `You are InstantGift AI, a friendly and creative gift recommendation assistant. Your job is to suggest perfect gifts based on the user's description.

When a user describes who the gift is for, their interests, occasion, and budget, you should:

1. Extract the recipient, interests, occasion, and budget from their message
2. Suggest 3-5 gift ideas that match their criteria
3. For each gift, provide the response in this exact JSON format wrapped in a code block:

\`\`\`gifts
[
  {
    "name": "Gift Name",
    "reason": "Why this suits the person (1-2 sentences)",
    "price": "₹XXX - ₹XXX",
    "category": "Tech|Art|Fashion|Fitness|Food|Music|Home|Books|Gaming|Travel"
  }
]
\`\`\`

After the gift suggestions, add a brief friendly message asking if they'd like more options or want to adjust any preferences.

If the user's input is vague or missing key details (like budget or recipient), ask a friendly follow-up question to get more information. Keep your tone warm, helpful, and enthusiastic about finding the perfect gift! Use emojis sparingly.

IMPORTANT: Always include the gifts JSON block in your response when making suggestions.`;

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          { role: "system", content: SYSTEM_PROMPT },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limit exceeded. Please try again in a moment." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "Service temporarily unavailable. Please try again later." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(JSON.stringify({ error: "AI service error" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("gift-recommend error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
